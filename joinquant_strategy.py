# 10. 金融股处理函数（熊市切换）
# ============================================================

def process_finance_stocks(context, data, index_df):
    """熊市金融股筛选与底仓建仓（PRD 3.1 / 3.3）

    修正记录（聚宽回测）：
    1) 原实现要求 rolling_percentile 样本数 >= settings.operation.valuation_min_samples
       （默认 60），但 PB 为季度频率，回测头几年窗口内样本仅 8~20 个，导致 pb_percentile
       恒为 None 直接 continue，金融股永不买入。现改用 rolling_percentile 默认阈值 8
       （与科技股 PE 分位一致，覆盖两年以上季度数据），样本仍严格只取 as_of 之前的正 PB，
       不引入未来函数。
    2) 原价格上限硬编码 20 元，把招商银行(30+)、宁波银行等高 PB 金融股误杀。现金融股
       单独放宽为 price_max_value（默认 200 元），仅剔除仙股与极端高价。
    3) 增加 data[code] 访问保护（停牌/非 universe 会抛异常），并把最便宜的过滤前置到
       指标计算之前，避免为将被淘汰的股票空算全部指标（性能）。
    4) 接入 evaluate_financial_stock（含 PB 分位 5→3→2 年降级窗口 + 可选模式），
       使金融股初筛与本地 stock_screener 语义一致，而非仅凭单一阈值判断。
    """
    # 获取当前底仓总仓位（金融股 + ETF）
    g.value_total_ratio = Decimal(str(
        sum(
            position.value
            for code, position in context.portfolio.positions.items()
            if code in g.finance_pool
        ) / context.portfolio.total_value
    ))
    log.info('金融池数量: {}，当前底仓比例: {}'.format(
        len(g.finance_pool), _pct(g.value_total_ratio)))
    valuation_date = pd.Timestamp(context.current_dt.date())
    v = settings.value

    for code in g.finance_pool:
        df = g.history_cache.get(code)
        if df is None or len(df) < 60:
            continue
        # 最便宜的过滤前置：停牌/ST/价格区间/成交量，全部在指标计算之前
        try:
            bar = data[code]
        except Exception:
            continue
        if bar.paused:
            continue
        if g.st_flags.get(code, [False])[0]:
            continue
        current_price = bar.close
        if current_price is None or current_price < 1 or current_price > 200:
            continue
        if bar.volume <= 0:
            continue

        # 清洗 close 缺失行后再计算指标
        df = df.dropna(subset=['close'])
        if len(df) < 60:
            continue
        df = add_all_indicators(df)

        # ---------- 获取 PB 及分位（无未来函数，样本不足返回 None） ----------
        pb = g.pb_snapshot.get(code)
        pb_percentile = None
        if pb is not None and pb > 0:
            if code not in g.pb_history:
                g.pb_history[code] = []
            g.pb_history[code].append((valuation_date, float(pb)))
            # 使用默认 min_samples=8（季度估值覆盖两年以上），而非配置的 60
            pb_percentile = rolling_percentile(
                g.pb_history[code], float(pb), valuation_date,
                v.pb_percentile_years,
            )
        # PB 缺失/分位算不出时：按 pb_percentile_optional 决定是否跳过该条件
        if pb_percentile is None and not v.pb_percentile_optional:
            continue

        # ---------- 调用金融股评估（PB 分位可选模式） ----------
        industry = "银行" if code in g.finance_pool else "非银金融"
        candidate = evaluate_financial_stock(df, code, industry, None)
        # evaluate_financial_stock 传入 valuation_df=None 时若 optional 会 passed=True；
        # 这里用我们已算好的 pb_percentile 复核 PB 阈值（保证用上历史缓存分位）
        if pb_percentile is not None and pb_percentile > v.pb_percentile_max:
            continue
        if not candidate.passed:
            # 若已有持仓但不再满足条件，清仓
            if code in context.portfolio.positions and context.portfolio.positions[code].total_amount > 0:
                order_target(code, 0)
                log.info('{} 金融股初筛未通过，清仓: {}'.format(code, candidate.failures))
            continue

        # ---------- 底仓仓位决策 ----------
        target_ratio = Decimal('0.05')  # 每只金融股计划仓位 5%（合计不超 40% 上限）
        current_ratio = Decimal(str(
            context.portfolio.positions[code].value / context.portfolio.total_value
        )) if code in context.portfolio.positions else Decimal(0)

        pb_pct = _as_decimal(pb_percentile)
        plan = decide_value_position('stock', pb_pct, target_ratio, current_ratio)
        action = plan.get('action')

        if action == 'BUY_INIT':
            requested = plan.get('ratio', Decimal(0))
            # 恐慌加仓：指数触发恐慌信号时额外加 10%
            if g.panic:
                requested = requested + plan_panic_add(target_ratio).get('ratio', Decimal(0))
            allowed, reason = apply_position_limits(
                requested, current_value_total=g.value_total_ratio, is_tech=False)
            if allowed > 0:
                order_value(code, context.portfolio.total_value * float(allowed))
                log.info('{} 执行底仓买入，金额: {:.2f}，PB分位: {}，原因: {}'.format(
                    code, context.portfolio.total_value * float(allowed),
                    _pct(pb_pct), plan.get('reason', '')))
        elif action == 'SELL':
            requested = plan.get('ratio', Decimal(0))
            if requested > 0 and code in context.portfolio.positions:
                order_value(code, -context.portfolio.total_value * float(requested))
                log.info('{} 执行底仓止盈，金额: {:.2f}，PB分位: {}'.format(
                    code, context.portfolio.total_value * float(requested), _pct(pb_pct)))