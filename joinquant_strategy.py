def to_decimal(v):
    if v is None or pd.isna(v):
        return None
    return Decimal(str(v))

def prepare_jq_data(raw_df, code):
    """
    将 attribute_history 返回的 DataFrame 转换为标准格式：
      - 重置索引，将日期转为 trade_date 列
      - 价格列转为 Decimal（你的函数要求）
    """
    if raw_df is None or raw_df.empty:
        return None
    df = raw_df.copy()
    # 将索引（日期）转为列 'date'
    df['date'] = df.index
    # 生成 trade_date 字符串列
    df['trade_date'] = df['date'].apply(lambda x: x.strftime('%Y-%m-%d'))
    # 价格列转 Decimal
    for col in ['open', 'high', 'low', 'close']:
        if col in df.columns:
            df[col] = df[col].apply(to_decimal)
    # 修正记录（聚宽回测）：get_price(fq="pre") 含停牌/除权产生的 NaN 与非正价，
    # 会令 _ensure_decimal 抛「价格列存在缺失值」→ evaluate_stock 静默 error→零交易。
    # 现统一剔除 close 缺失/非正行（对齐 data_layer 写侧净化）。
    df = df.dropna(subset=['close'])
    if len(df) == 0:
        return None
    if 'volume' in df.columns:
        df['volume'] = df['volume'].astype(float)
    return df

