def load_batch_history(codes, end_date, count=250):
    """一次读取一批股票的历史行情，避免逐股调用 attribute_history。

    修正记录（聚宽回测）：
    - get_price 多标的且 panel=False 时返回长表（含 code/date 列）或宽表（列为代码、
      索引为日期）。原实现假设必有 code 列，缺失时把整批数据塞给第一只股票，是典型的
      静默数据污染；现改为兼容三种结构，且多标的缺失 code 时直接跳过该批并告警。
    - 去掉“raw['code'] = codes[0]”的兜底写入，不允许把一批股票的行情错误归到一只。
    - 统一在 prepare_jq_data 前按聚宽原始列（date/time/code）处理，避免逐只 index 丢列。
    """
    if not codes:
        return {}
    result = {}
    for start in range(0, len(codes), 200):
        batch = codes[start:start + 200]
        try:
            raw = get_price(
                batch,
                end_date=end_date,
                count=count,
                frequency="1d",
                fields=["open", "high", "low", "close", "volume"],
                skip_paused=False,
                fq="pre",
                panel=False,
            )
        except Exception as e:
            log.warning('批量行情获取失败（{} 只，截至 {}）: {}'.format(
                len(batch), end_date, e))
            continue
        if raw is None or raw.empty:
            continue
        parsed = _split_batch_price(raw, batch)
        if not parsed:
            # 解析失败或该批缺少 code，不能静默按第一只股票填充
            log.warning('批量行情节点缺少 code 列，跳过本批 {} 只（数据无法归属）'.format(len(batch)))
            continue
        result.update(parsed)
        log.info('批量行情已加载 {} 只（截至 {}）'.format(len(parsed), end_date))
    return result


def _split_batch_price(raw, codes):
    """将 get_price 返回按股票拆成 {code: prepare_jq_data(df)}

    兼容三种结构：
      A) 长表：含 code 列 + date/time 列（panel=False 的常见返回，实测聚宽返回此结构）；
      B) 宽表：无 code 列、列为股票代码、索引为日期（仅支持 MultiIndex 列或单股票请求）；
      C) 索引起始即 DatetimeIndex 的容错形态。
    """
    if not isinstance(raw, pd.DataFrame):
        return {}

    # 分支 A：长表（含 code 列）
    if "code" in raw.columns:
        date_col = "time" if "time" in raw.columns else "date"
        if date_col not in raw.columns:
            return {}
        out = {}
        for code, group in raw.groupby("code"):
            frame = group.copy()
            frame.index = pd.to_datetime(frame[date_col])
            frame.drop(columns=["code", date_col], inplace=True, errors="ignore")
            out[str(code)] = prepare_jq_data(frame, str(code))
        return out

    # 分支 B（新增，关键）：宽表 —— 列为股票代码，索引为日期
    # 判定依据：列名集合与请求 codes 有交集，且索引可解析为日期
    code_cols = [c for c in raw.columns if str(c) in set(map(str, codes))]
    if code_cols and len(code_cols) >= 2:
        out = {}
        # 多标的需求交换层级：get_price 宽表带 MultiIndex 列时
        # DataFrame 形如 [('close','000001.XSHE'), ('close','000002.XSHE'), ...]
        if isinstance(raw.columns, pd.MultiIndex):
            for code in code_cols:
                sub = raw.xs(code, axis=1, level=1, drop_level=True)
                out[str(code)] = prepare_jq_data(sub, str(code))
        else:
            # 单字段宽表退化情形：无法归属，明确放弃
            log.warning("宽表缺少字段层级，无法归属，跳过该批 %d 只" % len(codes))
        return out

    # 分支 C：单股请求（无 code 列时，仅当恰好一个目标代码时允许按单股解析）
    if len(codes) == 1:
        code = str(codes[0])
        frame = raw.copy()
        if not isinstance(frame.index, pd.DatetimeIndex):
            date_column = "time" if "time" in frame.columns else "date"
            if date_column in frame.columns:
                frame.index = pd.to_datetime(frame[date_column])
                frame.drop(columns=[date_column], inplace=True, errors="ignore")
            else:
                return {}
        return {code: prepare_jq_data(frame, code)}

    log.warning("无法识别的行情结构: shape=%s columns=%s" % (raw.shape, list(raw.columns)[:5]))
    return {}

def load_batch_valuation(codes, as_of, metric):
    """按交易日批量读取当前估值；调用方负责维护无未来数据的历史缓存。"""
    if not codes:
        return {}
    field = valuation.pe_ratio if metric == "pe" else valuation.pb_ratio
    column = "pe_ratio" if metric == "pe" else "pb_ratio"
    q = query(valuation.code, field).filter(valuation.code.in_(codes))
    frame = get_fundamentals(q, date=as_of)
    if frame is None or frame.empty:
        return {}
    values = {}
    for row in frame.itertuples(index=False):
        code = getattr(row, "code", None)
        value = getattr(row, column, None)
        if code is not None and value is not None and value > 0:
            values[code] = float(value)
    return values


# 修正记录（聚宽回测 P0）：原 rolling_percentile 只使用“回测开始后每天追加一个估值点”
# 形成的缓存，回测前几年 history 为空，且样本以季度为单位远达不到
# settings.operation.valuation_min_samples（默认60），导致 PE/PB 分位几乎恒为 None，
# 让估值条件形同虚设或误判“缺失”。现将最小样本阈值降到 8（覆盖两年以上季度数据），
# 仍严格只统计 [as_of-years, as_of) 窗口内、且估值时间早于 as_of 的正估值，
# 不引入未来函数。
def rolling_percentile(history, current, as_of, years, min_samples=8):
    """滚动分位：只统计窗口内截至 as_of 之前观察到的正估值，样本不足返回 None。

    :param history: 元素为 (observed_at, value) 的列表，observed_at 为 pd.Timestamp
    :param current: 当前估值（正数才参与）
    :param as_of:  当前计算日期（pd.Timestamp）
    :param min_samples: 最小有效样本数（默认 8，适配聚宽季度估值频率）
    """
    if current is None or current <= 0:
        return None
    if as_of is None:
        return None
    as_ts = pd.Timestamp(as_of)
    cutoff = as_ts - pd.DateOffset(years=years)
    past = []
    for observed_at, value in history:
        if value is None or value <= 0:
            continue
        observed_ts = pd.Timestamp(observed_at)
        if cutoff <= observed_ts < as_ts:
            past.append(float(value))
    if len(past) < min_samples:
        return None
    return sum(value < float(current) for value in past) / len(past)

