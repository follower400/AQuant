            # （经 str 中转避免 float 二进制误差），从根上消除全脚本 float/Decimal 混算隐患。
            # 影响面：settings 下所有数值配置变为 Decimal。以下为「被当作整数使用」的
            # 字段，必须保持 int 语义：ma_period / macd_fast / macd_slow / macd_signal /
