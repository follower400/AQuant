def _pct(v):
    """比例转百分比字符串（如 0.045 -> 4.50%）；支持 None / float / Decimal"""
    if v is None:
        return "-"
    # 统一转为 Decimal
    if not isinstance(v, Decimal):
        v = Decimal(str(v))
    return f"{v * Decimal(100):.2f}%"

def _fmt(v):
    """Decimal/None/float 格式化输出（四舍五入 4 位小数，None 显示 -）"""
    if v is None:
        return "-"
    if not isinstance(v, Decimal):
        v = Decimal(str(v))
    return f"{v.quantize(Decimal('0.0001'))}"
    
