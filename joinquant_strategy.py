def process_tech_stocks(context, data, index_df):
    # 获取当前科技板块总仓位（用于上限校验）
    g.tech_total_ratio = Decimal(str(
        sum(
            position.value
            for code, position in context.portfolio.positions.items()
            if code in g.tech_pool
        ) / context.portfolio.total_value
    ))
    log.info('科技池数量: {}'.format(len(g.tech_pool)))
    
    valuation_date = pd.Timestamp(context.current_dt.date())
    for code in g.tech_pool:
        df = g.history_cache.get(code)
        if df is None or len(df) < 60:
            continue
        # 修正记录：data[code] 对停牌/非 universe 标的会抛异常，必须先行拦截；
        # 同时把最便宜的过滤（paused/ST/价格区间）提到指标计算之前，避免为将被
        # 淘汰的股票空算 6 条 MA + MACD + RSI（1408 只 × 250 行的 Decimal 循环）。
        try:
            bar = data[code]
        except Exception:
            continue
        if bar.paused:
            continue
        if g.st_flags.get(code, [False])[0]:
            continue
        current_price = bar.close
        if current_price is None or current_price < 1 or current_price > 20:
            continue
        if bar.volume <= 0:
            continue
        # ✅ 清洗：删除 close 为 NaN 或 None 的行
        df = df.dropna(subset=['close'])
        if len(df) < 60:
            log.info('{} 清洗后数据不足60日，跳过'.format(code))
            continue

        # 现在再补齐指标
        df = add_all_indicators(df)

        # 9.3 获取估值数据并计算 PE 分位
        # 修正记录（聚宽回测）：原传 settings.operation.valuation_min_samples(默认60)，
        # 但聚宽按季度取估值，回测头几年窗口内样本仅 8~20 个，导致分位恒为 None，
        # PE 条件永远落入"缺失"分支。改传默认阈值 8，覆盖两年以上季度数据，且严格
        # 只统计 as_of 之前的正估值，不引入未来函数。
        pe = g.pe_snapshot.get(code)
        if pe is not None and pe > 0:
            if code not in g.pe_history:
                g.pe_history[code] = []
            g.pe_history[code].append((valuation_date, float(pe)))
            percentile = rolling_percentile(
                g.pe_history[code], float(pe), valuation_date,
                settings.tech.pe_percentile_years,
            )
        else:
            percentile = None

        # 9.4 构建 valuation_df（模拟，因为聚宽没有历史估值表，我们只用当前分位）
        # 如果你的 evaluate_stock 需要 valuation_df，可以传 None，然后内部改为用传入的 percentile
        # 这里为了兼容，我们构造一个只有一行数据的 DataFrame
        val_df = None

        # 9.5 调用单票评估（你的 evaluate_stock）
        # 注意：evaluate_stock 内部会调用 add_all_indicators，但我们已经算过了，可以传已计算的 df
        # 需要修改 evaluate_stock 允许传入已算好的 df，或者直接调用你的核心评估逻辑
        # 这里简化为直接调用你的函数（如果它内部重复计算也没关系，但为了性能，建议你改造 evaluate_stock 接受 precomputed）
        # 在粘贴 evaluate_stock 时，建议你增加一个参数 skip_indicator=True 来跳过重复计算
        industry = g.tech_industry.get(code, "电子")
        candidate = evaluate_stock(
            df, code, industry, val_df,
            pe_percentile_override=percentile,
            indicators_ready=True,
        )

        if not candidate.passed:
            log.info('{} 初筛未通过: error={} failures={}'.format(
            code, candidate.error, candidate.failures))
            # 未通过初筛：如果已有持仓，清仓
            if code in context.portfolio.positions and context.portfolio.positions[code].total_amount > 0:
                order_target(code, 0)
                log.info('{} 不满足初筛条件，清仓: {}'.format(code, candidate.failures))
            continue

        # 9.6 仓位决策（分批建仓）
        status = g.tech_status.get(code, {'batch_done': 0, 'entry_price': None})
        # 将 entry_price 转为 Decimal
        if status.get('entry_price') is not None:
            entry_price = Decimal(str(status['entry_price']))
        else:
            entry_price = None

        plan = decide_tech_batch(df, status['batch_done'], entry_price)
        action = plan.get('action')
        if action == 'NONE':
            continue

        # 计算当前该股票持仓比例
        pos = context.portfolio.positions[code]
        current_single_ratio = Decimal(str(pos.value / context.portfolio.total_value)) if pos.total_amount > 0 else Decimal(0)

        # 9.7 应用仓位上限校验
        requested = plan.get('ratio', Decimal(0))
        allowed, reason = apply_position_limits(
            requested,
            current_single=current_single_ratio,
            current_tech_total=g.tech_total_ratio,
            is_tech=True
        )

        if allowed <= 0:
            log.info('{} 请求加仓被上限拦截: {}'.format(code, reason))
            continue

        # 9.8 执行下单
        target_value = context.portfolio.total_value * float(allowed)
        if target_value > 0:
            order_value(code, target_value)
            # 更新状态
            if action == 'BUY_1ST':
                status['batch_done'] = 1
                status['entry_price'] = data[code].close
            elif action == 'BUY_2ND':
                status['batch_done'] = 2
            elif action == 'BUY_3RD':
                status['batch_done'] = 3
            g.tech_status[code] = status
            log.info('{} 执行 {}，金额: {:.2f}，原因: {}'.format(
                code, action, target_value, plan.get('reason', '')))

