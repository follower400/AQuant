def _to_d(v):
    """将数值转为 Decimal（兼容 float/Decimal/None）"""
    if v is None or pd.isna(v):
        raise ValueError("指标值为空，无法比较")
    return v if isinstance(v, Decimal) else Decimal(str(v))

def _closes(index_df:pd.DataFrame):
    """提取 close 列并转为 Decimal 列表"""
    return [_to_d(v) for v in index_df["close"]]
    
def _consecutive_down_days(index_df: pd.DataFrame, days: int) -> bool:
    """最近 days 日收盘价逐日下跌（每根均严格低于前一日收盘）"""
    if len(index_df) < days + 1:
        return False  # 样本不足，保守判定为未触发
    # 修正记录（聚宽回测）：原 `closes = _closes(...)` 因上一步编辑被误缩进到
    # `return False` 之后成为死代码，触发 UnboundLocalError。现已修正到块内、缩进与
    # 条件判断同级，保证 return False 分支之外一定会给 closes 赋值。
    closes = _closes(index_df)[-(days + 1):]
    # 修正记录（聚宽回测）：原 `all(closes[i] < closes[i-1] for i in ...)` 在聚宽
    # 日志中被打印为 <generator object _consecutive_down_days.<locals>.<genexpr>>，
    # 说明返回值未收敛为 bool（生成器表达式被意外返回）。现显式用 list 物化后
    # 用 all() 求值，并外层 bool() 兜底，保证永远返回 Python bool。
    # 影响面：is_half_position_triggered / is_panic_add_triggered 的返回值类型。
    return bool(all([closes[i] < closes[i - 1] for i in range(1, len(closes))]))
    
def _volume_confirm(index_df: pd.DataFrame) -> bool:
    """量能确认：当日成交量 >= 近 volume_ma_period 日均量 x volume_ratio

    修正记录（P2）：指数接口理论上有成交量列，但按 .coderrules 边缘情况要求，
    缺 volume 列时保守视为「量能不确认」（不判 BULL），严禁直接访问属性抛错。
    """
    mr = settings.market_regime
    if "volume" not in index_df.columns or index_df["volume"].isna().all():
        return False
    vols = [_to_d(v) for v in index_df["volume"].tail(mr.volume_ma_period)]
    if not vols:
        return False
    avg = sum(vols) / Decimal(len(vols))
    latest_vol = _to_d(index_df["volume"].iloc[-1])
    return latest_vol >= avg * _to_d(mr.volume_ratio)
    
def _volume_ma5_ok(kline_df: pd.DataFrame, ratio: Decimal) -> bool:
    """量能确认：当日成交量 >= 近5日均量 x ratio；缺 volume 列保守视为不满足"""
    if "volume" not in kline_df.columns or len(kline_df) < 5:
        return False
    vols = [_to_d(v) for v in kline_df["volume"].tail(5)]
    avg = sum(vols) / Decimal(len(vols))
    return _to_d(kline_df["volume"].iloc[-1]) >= avg * ratio
    
