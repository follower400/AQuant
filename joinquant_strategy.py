def _check_input(df, column):
    """输入校验：必须是 DataFrame 且包含目标列"""
    if not isinstance(df, pd.DataFrame):
        raise TypeError(f"输入必须是 pandas DataFrame，实际为 {type(df).__name__}")
    if column not in df.columns:
        raise ValueError(f"DataFrame 缺少必需列: {column}")
    if len(df) < 2:
        raise ValueError("数据行数不足，至少需要 2 行")

def _ensure_decimal(series):
    """将价格列转为 Decimal 列表（缺失值抛错）"""
    from decimal import Decimal
    out = []
    for v in series:
        if isinstance(v, Decimal):
            out.append(v)
        elif v is None or pd.isna(v):
            raise ValueError("价格列存在缺失值，因子计算前请先清洗数据")
        else:
            out.append(Decimal(str(v)))
    return out
    
def _decimal_std(values):
    """样本标准差（Decimal，n-1 分母）"""
    n = len(values)
    if n < 2:
        return Decimal(0)  # 防止除零
    mean = sum(values) / Decimal(n)
    var = sum((v - mean) ** 2 for v in values) / Decimal(n - 1)
    return var.sqrt()
    
def _sub_months(d: date, months: int) -> date:
    """日期减 N 个月（月末日期自动收缩到当月最后一天）"""
    total = d.year * 12 + (d.month - 1) - months
    y, m = divmod(total, 12)
    day = min(d.day, calendar.monthrange(y, m + 1)[1])
    return date(y, m + 1, day)
    
def _sub_years(d: date, years: int) -> date:
    """日期减 N 年；2 月 29 日等边界回退到当月 28 日，避免 replace 抛错"""
    try:
        return d.replace(year=d.year - years)
    except ValueError:
        return d.replace(year=d.year - years, day=28)
    
def _as_decimal(v) -> Optional[Decimal]:
    """任意数值/None 转 Decimal；None/NaN 返回 None"""
    if v is None or pd.isna(v):
        return None
    return v if isinstance(v, Decimal) else Decimal(str(v))

def _ensure_decimal_optional(series) -> List[Optional[Decimal]]:
    """将一列数值转为 Decimal 列表；缺失/NaN 返回 None（不抛错）"""
    out: List[Optional[Decimal]] = []
    for v in series:
        out.append(_as_decimal(v))
    return out

def _to_date(d) -> date:
    """将 str / datetime / date / pandas.Timestamp 统一转为 date 对象"""
    if isinstance(d, datetime):
        return d.date()
    if isinstance(d, date):
        return d
    # pandas.Timestamp 是 datetime 子类，已被上面分支捕获；此处兜底字符串解析
    s = str(d)[:10]
    return datetime.strptime(s, "%Y-%m-%d").date()

def _has_limit_up_recent(kline_df: pd.DataFrame, months: int, threshold: Decimal) -> bool:
    """近 months 个月（自然月）内是否出现至少 1 次涨停（单日涨幅 >= threshold）

    遍历窗口内所有交易日的前后收盘对比；样本不足 2 日时保守返回 False。
    """
    if len(kline_df) < 2:
        return False
    try:
        latest_date = datetime.strptime(str(kline_df["trade_date"].iloc[-1])[:10],
                                        "%Y-%m-%d").date()
    except (ValueError, TypeError):
        return False
    cutoff = _sub_months(latest_date, months)
    prev: Optional[Decimal] = None
    for row in kline_df.itertuples(index=False):
        try:
            d = datetime.strptime(str(row.trade_date)[:10], "%Y-%m-%d").date()
        except (ValueError, TypeError):
            continue
        if d < cutoff:
            prev = _as_decimal(getattr(row, "close", None))
            continue
        close = _as_decimal(getattr(row, "close", None))
        if prev is not None and close is not None and prev > 0:
            rise = (close - prev) / prev
            if rise >= threshold:
                return True
        prev = close
    return False
    
