def is_panic_add_triggered(index_df: pd.DataFrame) -> bool:
    """恐慌加仓触发（PRD 3.3）：沪深300 单日跌超 3% 或 连续 3 日下跌（供底仓加仓引用）"""
    # 修改点1：内联校验
    if not isinstance(index_df, pd.DataFrame) or index_df.empty:
        return False
    if "close" not in index_df.columns:
        return False
    # 修改点2：使用全局 settings
    value = settings.value

    if len(index_df) < 2:
        return False
    # 修正记录（聚宽回测 P0）：上一轮编辑把本行多缩进 4 格，导致 closes 未在函数作用域
    # 内赋值，调用时抛 UnboundLocalError: local variable 'closes' referenced before
    # assignment（聚宽 user_code.py:762），整个 handle_data 中断，全天不再交易。
    # 现已修正缩进至函数体一级，与 if 语句同级。
    closes = _closes(index_df)
    one_day_crash = (closes[-2] - closes[-1]) / closes[-2] > _to_d(value.panic_drop_1d)
    
    # 修正记录（聚宽回测）：原 `return one_day_crash or _consecutive_down_days(...)`
    # 若左侧为 numpy.bool_/Decimal 比较结果，or 可能把右侧生成器直接返回，
    # 导致 handle_data 日志打印 panic=<generator object ...>。现强制 bool() 收敛。
    # 影响面：panic 标志类型（bool），金融股恐慌加仓判定分支。
    return bool(one_day_crash) or bool(_consecutive_down_days(index_df, value.panic_drop_days))
    
def _percentile_with_fallback(valuation_df: Optional[pd.DataFrame], column: str,
                              years: int) -> tuple:
    """估值分位计算（含降级窗口）：配置年限 → 3 年 → 2 年逐级尝试

    :return: (percentile, window_used, missing_reason)；成功时 reason 为 ""
    """
    if valuation_df is None or valuation_df.empty:
        return None, None, "估值数据为空（百度接口无数据或拉取失败）"
    for win in sorted(set([years, 3, 2]), reverse=True):
        try:
            valuation_percentile(valuation_df, column=column, years=win)
            val = _as_decimal(valuation_df[f"{column}_percentile_{win}y"].iloc[-1])
            if val is not None:
                return val, win, ""
        except Exception:
            continue
    return None, None, f"估值数据仅 {len(valuation_df)} 行，全部窗口均无法计算"


