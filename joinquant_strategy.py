def handle_data(context, data):
    trade_date = pd.Timestamp(context.current_dt.date())
    if g.last_cache_date != trade_date:
        g.last_cache_date = trade_date
        g.history_cache = load_batch_history(
            list(set(g.tech_pool + g.finance_pool)), context.current_dt
        )
        g.pe_snapshot = load_batch_valuation(g.tech_pool, context.current_dt, "pe")
        g.pb_snapshot = load_batch_valuation(g.finance_pool, context.current_dt, "pb")
        today = context.current_dt.strftime("%Y-%m-%d")
        g.st_flags = get_extras(
            "is_st",
            list(set(g.tech_pool + g.finance_pool)),
            start_date=today,
            end_date=today,
            df=False,
        )
    # ---------- 8.1 获取指数数据，判定宏观市场状态 ----------
    index_raw = attribute_history('000300.XSHG', 250, '1d', ['close', 'volume'])
    if index_raw is None or index_raw.empty:
        log.warning('获取沪深300数据失败，跳过今日')
        return
    index_df = prepare_jq_data(index_raw, '000300')
    if index_df is None or len(index_df) < 60:
        log.warning('指数数据不足60日，跳过')
        return
    # 补齐指标
    index_df = add_all_indicators(index_df)
    # 调用市场判定（全部强制 bool，避免打印出生成器对象）
    g.regime = detect_regime(index_df)
    g.force_reduce = bool(is_force_reduce_triggered(index_df))
    g.panic = bool(is_panic_add_triggered(index_df))
    clear_tech = bool(is_clear_tech_triggered(index_df))

    log.info('宏观状态: regime={}, force_reduce={}, panic={}, clear_tech={}'.format(
        g.regime, g.force_reduce, g.panic, clear_tech))

    # ---------- 8.2 全局风控：禁止开仓检查 ----------
    forbid_open = is_forbid_open(index_df)
    # 修正记录（聚宽回测 P0，核心）：原分支链 if clear_tech / elif BEAR / elif forbid
    # 把 clear_tech 作为一票否决，且跌势中 clear_tech 恒为 True（沪深300 长期在 MA120
    # 下方），导致：①科技股永不开仓（符合 PRD）；②金融股分支被完全屏蔽（违背 PRD）——
    # PRD 4.3 与第 6 节要求"清仓科技 → 布局低 PB 金融"的熊市防御闭环。实测 2023-12-21
    # 至 2024-01-12 全程 clear_tech=True，金融股从未被筛选，故零交易。
    # 现改为：clear_tech 时先清仓科技，再落入金融股筛选分支（与 BEAR 合并处理）。
    # 影响面：熊市/跌破 MA120 期间的开仓行为，科技股清仓逻辑不变。
    if clear_tech:
        log.info('触发科技股清仓，清理现有科技持仓并切换金融股防御筛选')
        for code, position in context.portfolio.positions.items():
            if code in g.tech_pool and position.total_amount > 0:
                order_target(code, 0)
                log.info('强制清仓: {}'.format(code))
        process_finance_stocks(context, data, index_df)
    elif g.regime == 'BEAR':
        log.info('进入熊市防御模式 → 执行金融股筛选')
        process_finance_stocks(context, data, index_df)
    elif forbid_open:
        log.info('触发禁止开仓条件，今日不执行科技股新仓')
    else:
        log.info('正常模式 → 执行科技股筛选与分批建仓')
        process_tech_stocks(context, data, index_df)

    # ---------- 8.4 额外：强制减仓处理 ----------
    if g.force_reduce:
        log.info('触发强制减仓（指数连跌超3%），减仓科技板块')
        # 这里可以减仓科技股总持仓的 50% 或全部清掉
        for code in list(context.portfolio.positions.keys()):
            if code in g.tech_pool:
                current_amount = context.portfolio.positions[code].total_amount
                if current_amount > 0:
                    # 减半
                    order_target_value(code, context.portfolio.positions[code].value * 0.5)
                    log.info('强制减仓: {} 减半'.format(code))

